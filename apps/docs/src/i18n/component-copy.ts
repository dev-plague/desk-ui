export const COMPONENT_COPY = { es, en };

export function getComponentCopy<S extends keyof ComponentCopy>(
  slug: S,
  locale: Locale,
): ComponentCopy[S] {
  return COMPONENT_COPY[locale][slug];
}

export function useComponentCopy<S extends keyof ComponentCopy>(
  slug: S,
): ComponentCopy[S] {
  const { locale } = useI18n();
  return getComponentCopy(slug, locale);
}

export function formatCopy(
  template: string,
  vars: Record<string, string | number>,
): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
